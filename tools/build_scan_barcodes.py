#!/usr/bin/env python3
"""Build scan/barcodes.js (barcode -> brand, code, name, range) for Scan paints.

Source: Paint Commons catalog (https://github.com/paintcommons/catalog), data CC0 1.0. Snapshot at commit 46946c5 kept in
/mnt/project-files/data/import-sources/paintcommons-catalog@46946c5/. Only barcodes are taken (never colours). Each barcode is
either published on a manufacturer/retailer listing (source_url kept there), calculated from the product code (Army Painter,
Vallejo), or confirmed by a reviewed scan. The site matches brand + code + name to its own paints when a barcode is scanned,
with the same matcher the CSV import uses, and the person still confirms before anything is added.

Usage: python3 tools/build_scan_barcodes.py <catalog folder>
"""
import glob, json, os, sys

def ean_ok(s):
    if not s.isdigit() or len(s) not in (8, 12, 13): return False
    d = [int(c) for c in s.zfill(13)] if len(s) != 8 else [int(c) for c in s]
    body, chk = d[:-1], d[-1]
    w = [3, 1] if len(d) == 8 else [1, 3]
    t = sum(x * w[i % 2] for i, x in enumerate(body))
    return (10 - t % 10) % 10 == chk

src = sys.argv[1]
out, n_bad = {}, 0
for f in sorted(glob.glob(os.path.join(src, 'paints', '*', '*.json'))):
    for p in json.load(open(f, encoding='utf-8')):
        for b in p.get('barcodes') or []:
            e = str(b.get('ean', '')).strip()
            if b.get('source') not in ('published', 'calculated', 'scan') or not ean_ok(e):
                n_bad += 1; continue
            if len(e) == 12: e = '0' + e  # UPC-A read as EAN-13
            row = [p['brand'], p.get('code') or '', p['name'], p.get('range') or '']
            if e in out and out[e] != row: out[e] = None  # same barcode on two different paints: don't trust it
            elif e not in out: out[e] = row
clean = {k: v for k, v in sorted(out.items()) if v}
js = ('// Generated by tools/build_scan_barcodes.py from the Paint Commons catalog (CC0 1.0, github.com/paintcommons/catalog).\n'
      '// Barcode -> [brand, code, name, range]. Used only by Scan paints; matched to our own paints when scanned. Do not edit by hand.\n'
      'var SCAN_BC=' + json.dumps(clean, ensure_ascii=False, separators=(',', ':')) + ';\n')
open('scan/barcodes.js', 'w', encoding='utf-8').write(js)
print(len(clean), 'barcodes;', n_bad, 'skipped;', len(out) - len(clean), 'clashing')
